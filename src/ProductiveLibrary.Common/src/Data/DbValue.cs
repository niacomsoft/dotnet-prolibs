namespace Niacomsoft.ProductiveLibrary.Data
{
  /// <summary> 提供了一组预置的数据库默认值相关的静态 <see langword="static" /> 方法。 </summary>
  public static class DbValue
  {
    #region Constants

    /// <summary> 等效 <see langword="false" /> 的整型值。 </summary>
    public const int False = 0;

    /// <summary> 表示女性的默认整型值。 </summary>
    public const int Female = 2;

    /// <summary> 表示男性的默认整型值。 </summary>
    public const int Male = 1;

    /// <summary> 等效 <see langword="true" /> 的整型值。 </summary>
    public const int True = 1;

    /// <summary> 表示未定义的默认整型值。 </summary>
    public const int Undefined = -1;

    /// <summary> 表示未知的默认整型值。 </summary>
    public const int Unknown = -1;

    /// <summary> 表示未指定的默认整型值。 </summary>
    public const int Unspecified = -1;

    /// <summary> 表示未提供的默认整型值。 </summary>
    public const int Unsupported = -1;

    #endregion Constants
  }
}